def ang_dist_deg(az1, el1, az2, el2):
    a1, e1, a2, e2 = map(np.deg2rad, (az1, el1, az2, el2))
    c = np.sin(e1) * np.sin(e2) + np.cos(e1) * np.cos(e2) * np.cos(a1 - a2)
    return float(np.degrees(np.arccos(np.clip(c, -1.0, 1.0))))


